#: the seven surfaces ``room_to_rgb`` indexes with, in ITS order (``surfaces[room[i, j]]``)
TILE_NAMES = ("wall", "floor", "box_target", "box_on_target", "box", "player", "player_on_target")
N_TILE = len(TILE_NAMES)
TILE_PX = 16

#: tile id -> (room_state, room_fixed). The inverse of the join ``room_to_rgb`` computes; asserted
#: against the reference on every driven state rather than trusted.
ROOM_STATE_OF = (0, 1, 2, 3, 4, 5, 5)
ROOM_FIXED_OF = (0, 1, 2, 2, 1, 1, 2)

#: The ten colours of the atlas, in ascending order, each named by WHERE it is painted -- measured in
#: the frozen measurement record, which prints the pixel count and bounding box of every colour
#: in every tile. Three near-identical reds and three near-identical box shades are separate labels
#: because they are separate colours in the art, not because they mean different things.
PALETTE_NAMES = (
    "background",
    "player",
    "wall_brick",
    "wall_mortar",
    "box_dark",
    "box_mid",
    "box_light",
    "target_dark",
    "target_mid",
    "target_light",
)
OFFICIAL_PALETTE = (
    (0, 0, 0),
    (41, 202, 26),
    (176, 61, 0),
    (176, 154, 142),
    (215, 103, 0),
    (215, 114, 0),
    (215, 196, 0),
    (238, 0, 0),
    (239, 22, 22),
    (242, 26, 26),
)
N_LABEL = len(PALETTE_NAMES)

#: ``CHANGE_COORDINATES``: action-1 mod 4 -> (d_row, d_col). Up, down, left, right.
CHANGE = ((-1, 0), (1, 0), (0, -1), (0, 1))
N_ACTIONS = 9

#: ``SokobanEnv``'s own defaults, at module scope because a class body cannot see its own names from
#: inside a comprehension and ``state_names`` is one
ROOM_H, ROOM_W = 10, 10
N_CELLS = ROOM_H * ROOM_W
CELL_NAMES = tuple(f"cell[{r},{c}]" for r in range(ROOM_H) for c in range(ROOM_W))


def _tile_dir() -> str:
    """Where ``gym_sokoban``'s seven PNGs live, located WITHOUT importing the package.

    ``import gym_sokoban`` executes a package whose only job is to register its ids with the legacy
    ``gym``, which emits a deprecation banner and pulls a second RL framework into the process for the
    sake of seven image files. ``find_spec`` locates the package without running any of it.
    """
    spec = importlib.util.find_spec("gym_sokoban")
    if spec is None or not spec.submodule_search_locations:
        raise ImportError(
            "gym-sokoban is not installed. The seven 16x16 tile images ARE this env -- the frame is a "
            "gather from them and nothing here re-derives them -- so there is no degraded mode to fall "
            "back to. `pip install gym-sokoban`."
        )
    return os.path.join(list(spec.submodule_search_locations)[0], "envs", "surface")


def _build_atlas():
    """``(7,16,16,3)`` uint8 tiles from the shipped PNGs, plus the label map for recolouring.

    The RGB tiles come straight out of the assets, so exactness is by construction. The label map says
    which of the ten palette entries painted each pixel, which is what makes a RECOLOURED atlas exact
    as well: there is no supersampling and no box filter anywhere in ``room_to_rgb``, so
    ``palette[label]`` is not an approximation of a tile, it IS the tile. Both assertions below fire
    at import rather than at render time, because a wrong palette constant is invisible under the
    default appearance -- which is the only one parity is measured under.
    """
    import imageio.v2 as imageio

    root = _tile_dir()
    missing = [n for n in TILE_NAMES if not os.path.exists(os.path.join(root, f"{n}.png"))]
    if missing:
        raise ImportError(
            f"gym-sokoban is installed at {root} but {len(missing)} of its seven tile images are "
            f"missing ({', '.join(missing)}). The frame is a gather from those files; a wheel that "
            f"ships the code without the art cannot render this env."
        )
    rgb = np.stack([np.asarray(imageio.imread(os.path.join(root, f"{n}.png")))[..., :3] for n in TILE_NAMES]).astype(
        np.uint8
    )
    pal = np.asarray(OFFICIAL_PALETTE, np.uint8)
    labels = np.full(rgb.shape[:3], 255, np.uint8)
    for k, c in enumerate(pal):
        labels[(rgb == c).all(-1)] = k
    if (labels == 255).any():
        found = np.unique(rgb.reshape(-1, 3), axis=0)
        raise AssertionError(
            f"the shipped tiles use colours OFFICIAL_PALETTE does not name: the atlas has "
            f"{len(found)} distinct colours and the palette names {len(pal)}. Every recoloured "
            f"frame would be wrong in a way no parity test would catch, because parity is measured "
            f"at the default palette where the label map is unused."
        )
    if not np.array_equal(pal[labels], rgb):
        raise AssertionError("palette[labels] does not reproduce the official tiles")
    return rgb, labels


def _check_sokoban_works() -> None:
    """Probe the whole runtime AT IMPORT, so a machine without it loses this env cleanly.

    ``import X`` succeeding is not the same as X working, and neither is X being importable the same
    as this env being renderable. Three separate things have to hold and each fails differently:

      * ``imageio`` and the seven PNGs, because the atlas is built from them and there is no fallback;
      * ``SokobanEnv`` itself, because ``sample_states`` draws from real rollouts of it and
        ``reference_render`` needs it -- an env that renders but cannot produce a state is not usable;
      * neither of those is checked by importing this module, so both are checked here.

    Raising ``ImportError`` is what makes the failure clean: ``stable_envs/envs/__init__.py``'s
    auto-discovery catches it, ``import_errors()`` names it, and the conformance suite prints it. The
    alternative -- registering anyway -- was measured: 15 test failures from one missing package, all
    of them raised inside a fixture where they look like a broken env rather than an absent one.

    ``reset=False`` because a room costs a reverse-play search; what is being probed is that the class
    constructs, not that it can generate a level.
    """
    _build_atlas()
    import warnings

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # the legacy gym deprecation banner
        try:
            from gym_sokoban.envs.sokoban_env import SokobanEnv

            SokobanEnv(dim_room=(ROOM_H, ROOM_W), num_boxes=4, reset=False)
        except ImportError:
            raise
        except Exception as e:  # noqa: BLE001
            raise ImportError(
                f"gym-sokoban is installed but SokobanEnv does not construct: {type(e).__name__}: "
                f"{e}. It installs against the legacy `gym`, which does not support NumPy 2.0, so a "
                f"skew there presents here."
            ) from e


_check_sokoban_works()


class _Atlas:
    """The 7-tile atlas and its label decomposition, built once per process.

    Not cached on disk: it is seven 16x16 PNGs, and a cache would only add a way for the atlas to be
    stale or corrupt while removing nothing -- the package has to be present anyway, because
    ``sample_states`` rolls the official env out.
    """

    _mem: dict[str, _Atlas] = {}

    def __init__(self, device="cuda"):
        rgb, labels = _build_atlas()
        self.device = torch.device(device)
        self.rgb = torch.from_numpy(rgb).to(self.device)  # (7,16,16,3) uint8
        self.labels = torch.from_numpy(labels).to(self.device)  # (7,16,16) uint8

    @classmethod
    def get(cls, device="cuda") -> _Atlas:
        key = str(device)
        if key not in cls._mem:
            cls._mem[key] = cls(device)
        return cls._mem[key]


@register
class Sokoban(Env):
    """Sokoban-v0: a 10x10 room with 4 boxes, rendered as a gather from a 7-tile atlas.

    State: one index per cell into the seven tiles, so a 10x10 room is 100 numbers against a
    160x160x3 = 76,800-byte frame (**768x**, or 3,072x at the one byte per cell the alphabet needs).
    """

    name = "sokoban"
    reference_id = "Sokoban-v0"
    #: ``SokobanEnv`` defaults; the room shape fixes ``state_dim`` and the frame size
    ROOM_H, ROOM_W = ROOM_H, ROOM_W
    NUM_BOXES = 4
    MAX_STEPS = 120
    default_size = ROOM_H * TILE_PX
    state_dim = N_CELLS
    state_names = CELL_NAMES
    #: Public state: one key, because the state IS one grid — the room, in this
    #: module's seven-tile alphabet. Every column is covered at its unchanged offset, so nothing is
    #: hidden, ``_hidden_state`` is never consulted and the frozen layout does not move. Unlike
    #: MiniGrid there is no carried object and no hidden variable of any kind: a stored Sokoban state
    #: determines its own continuation exactly, which is what ``step``'s docstring claims and what
    #: makes ``transition`` pure with nothing to splice back in.
    state_layout = ((("cells",), N_CELLS, 0),)

    #: nine actions: 0 no-op, 1-4 push up/down/left/right, 5-8 move up/down/left/right. A policy emits
    #: one float per environment and ``step`` floors it, so the half-open [0, 9) bounds make
    #: ``RandomPolicy`` uniform over the nine.
    action_dim = 1
    action_low = 0.0
    action_high = float(N_ACTIONS)
    step_reference_checkable = True
    step_reference_exact = True
    #: 1, not the PushT default of 8: a push held for eight steps just walks into the same wall, and
    #: what a decision table needs is coverage of the transitions rather than sustained pressure.
    step_reference_hold = 1
    step_reference_groups = (("cells", tuple(range(N_CELLS)), "abs"),)

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self.atlas = _Atlas.get(device=self.device)
        self._pool: np.ndarray | None = None
        self._pool_has: np.ndarray | None = None
        self._default_t: torch.Tensor | None = None
        self._rgb_cache = _RES.BoundedCache(8, name="sokoban.rgb")
        dev = self.device
        self._state_of = torch.tensor(ROOM_STATE_OF, dtype=torch.long, device=dev)
        self._fixed_of = torch.tensor(ROOM_FIXED_OF, dtype=torch.long, device=dev)
        self._change = torch.tensor(CHANGE, dtype=torch.long, device=dev)
        self._act = torch.zeros(self.B, self.action_dim, device=dev, dtype=torch.float32)

    # --- geometry ---------------------------------------------------------------------------------

    def _scale(self, size: int) -> int:
        """Integer pixel-replication factor for one output size, or an error naming the legal ones.

        ``room_to_rgb`` has no tile-size parameter: the art is 16x16 and there is no reference frame at
        any other resolution. A whole-number replication of it is still exactly what the reference
        draws, one pixel becoming k x k, so those sizes are offered and nothing else is -- a resample
        would be a picture the reference never produces, dressed as the same env.
        """
        t, r = divmod(int(size), self.ROOM_H)
        k, r2 = divmod(t, TILE_PX)
        if r or r2 or k < 1:
            raise ValueError(
                f"Sokoban renders at whole multiples of its 16 px art only: size must be "
                f"{self.ROOM_H * TILE_PX} x k for an integer k >= 1, got {size}"
            )
        return k

    # --- variation --------------------------------------------------------------------------------

    def make_variation_space(self) -> Dict:
        """The ten colours of the atlas, each its own knob, defaulting to the shipped art.

        Ten RGB leaves rather than one packed palette, and that is a claim about this renderer:
        ``room_to_rgb`` composites nothing -- it assigns whole tiles into a uint8 buffer -- so every
        pixel has exactly one writer and a knob set to a colour puts THAT colour in the frame, not a
        blend of it. ``check_colors_apply_exactly`` is therefore a meaningful check here, which it is
        not for MiniGrid (whose every tile is downsampled and, in the POV view, blended with the
        field-of-view overlay).
        """
        return Dict({"palette": Dict({n: RGBBox(init_value=c) for n, c in zip(PALETTE_NAMES, OFFICIAL_PALETTE)})})

    # --- rendering --------------------------------------------------------------------------------

    def _palette(self, sty) -> torch.Tensor:
        """``(B, 10, 3)`` float: the colour each label paints, per environment."""
        return torch.stack([torch.trunc(sty[f"palette.{n}"]) for n in PALETTE_NAMES], 1)

    def _is_default(self, sty) -> bool:
        if self._default_t is None:
            self._default_t = torch.as_tensor(self.default_style(), device=self.device, dtype=torch.float32)
        return bool((sty.values[0] == self._default_t).all())

    def _shared_rgb(self, sty, k: int) -> torch.Tensor:
        """The (7, 16k, 16k, 3) atlas for one shared appearance, memoised on the style bytes."""
        row = sty.values[0]
        key = np.ascontiguousarray(row.detach().cpu().numpy()).tobytes() + bytes([k])
        hit = self._rgb_cache.get(key)
        if hit is not None:
            return hit
        base = (
            self.atlas.rgb
            if self._is_default(sty)
            else self._palette(sty)[0].to(torch.uint8)[self.atlas.labels.long()]
        )
        out = (base if k == 1 else base.repeat_interleave(k, 1).repeat_interleave(k, 2)).contiguous()
        return self._rgb_cache.put(key, out)

    @torch.no_grad()
    def render(
        self,
        states=None,
        size: int | None = None,
        supersample: int | None = None,
        variation: dict | None = None,
        style=None,
        out=None,
    ) -> torch.Tensor:
        """``(...,100)`` -> ``(...,160,160,3)`` uint8 on device. A gather, with no rasterisation."""
        if supersample not in (None, 1):
            raise ValueError(
                f"Sokoban: supersample={supersample} is not available. The frame is a gather from "
                f"16x16 bitmaps, so there is no coverage to sample twice -- ask for a larger `size`, "
                f"which replicates each art pixel k x k exactly."
            )
        s = self._state if states is None else torch.as_tensor(states, device=self.device, dtype=torch.float32)
        lead = tuple(s.shape[:-1])
        s = s.reshape(-1, self.state_dim)
        k = self._scale(int(size or self.size))
        T = TILE_PX * k
        sty = self.resolve_style(style, variation, batch=int(s.shape[0]))
        idx = self._tile_indices(s)
        flat = None
        if out is not None:
            flat = out.reshape(-1, self.ROOM_H * T, self.ROOM_W * T, 3)
        if sty.shared:
            img = tm.blit(self._shared_rgb(sty, k), idx, T, out=flat)
        else:
            img = self._blit_styled(idx, sty, k, flat)
        return img.reshape(*lead, *img.shape[1:]) if lead else img

    def _blit_styled(self, idx: torch.Tensor, sty, k: int, out) -> torch.Tensor:
        """Per-environment palettes: gather LABELS, then colour them per environment.

        The shared path cannot express this -- an atlas is keyed on a palette, so B palettes would mean
        B atlases -- and there is nothing to reconcile between the two paths here, because the
        recolouring has no filter in it: both compute ``palette[label]`` for every output pixel and
        differ only in whether the lookup happens before or after the gather.
        """
        B, H, W = idx.shape
        lab = self.atlas.labels.long()[idx.long()]  # (B,H,W,16,16)
        lab = lab.permute(0, 1, 3, 2, 4).reshape(B, H * TILE_PX, W * TILE_PX)
        pal = self._palette(sty).to(torch.uint8)  # (B,10,3)
        img = pal[torch.arange(B, device=idx.device).view(B, 1, 1), lab]
        if k > 1:
            img = img.repeat_interleave(k, 1).repeat_interleave(k, 2)
        img = img.contiguous()
        if out is not None:
            out.copy_(img)
            return out
        return img

    def _tile_indices(self, s: torch.Tensor) -> torch.Tensor:
        """``(B,100)`` float cell codes -> ``(B,10,10)`` int32 atlas slots.

        Wrapping rather than clamping, for the reason MiniGrid wraps: the conformance suite proves a
        dimension reaches the render by moving it, and a clamp would pin an already-large code in place
        and report a live dimension as dead.
        """
        idx = torch.round(s).long() % N_TILE
        return idx.reshape(-1, self.ROOM_H, self.ROOM_W).to(torch.int32)

    # --- physics ----------------------------------------------------------------------------------

    def _advance(self) -> None:
        """The env's OWN buffers advanced one step, at fixed addresses."""
        self._advance_into(self._state, self._act)

    def _step_state(self) -> TensorDict:
        """Snapshot the live cells with one copy for the hot ``step`` return path."""
        n = self._live_rows
        return TensorDict(
            {"cells": self._state[:n].clone()},
            batch_size=[n],
            device=self.device,
        )

    def _advance_into(self, s, act) -> None:
        """``SokobanEnv.step`` for the whole batch, as one straight-line sequence of masked writes.

        Writes IN PLACE into the two buffers it is given rather than into ``self``, which is what
        lets ``transition`` be pure while ``step`` keeps writing the env's own: one body, two
        callers, and no second copy of the decision table to drift from this one.

        Every branch of the reference's dispatch is evaluated for every environment and selected by a
        mask, because a batch holds all nine actions at once. The branches are mutually exclusive on
        the action, so the writes cannot collide.

        The one thing this decides that the reference does not: a target cell outside the grid. See the
        module docstring -- it is unreachable in a generated room, and it is treated as a wall here.
        """
        H, W = self.ROOM_H, self.ROOM_W
        a = act[:, 0].floor().clamp(0, N_ACTIONS - 1).long()
        tile = torch.round(s).long() % N_TILE
        st = self._state_of[tile]  # room_state
        fx = self._fixed_of[tile]  # room_fixed

        # the player is wherever room_state == 5; argmax picks the first, exactly as
        # ``np.argwhere(self.room_state == 5)[0]`` does
        p = (st == 5).to(torch.float32).argmax(dim=1)
        pr, pc = p // W, p % W
        d = self._change[(a - 1).clamp_min(0) % 4]
        nr, nc = pr + d[:, 0], pc + d[:, 1]
        br, bc = nr + d[:, 0], nc + d[:, 1]
        n_in = (nr >= 0) & (nr < H) & (nc >= 0) & (nc < W)
        b_in = (br >= 0) & (br < H) & (bc >= 0) & (bc < W)
        ni = (nr.clamp(0, H - 1) * W + nc.clamp(0, W - 1)).unsqueeze(1)
        bi = (br.clamp(0, H - 1) * W + bc.clamp(0, W - 1)).unsqueeze(1)
        z = torch.zeros_like(pr)
        # out of bounds behaves as a wall: state 0, which is in neither [3,4] nor [1,2]
        n_st = torch.where(n_in, st.gather(1, ni).squeeze(1), z)
        n_fx = torch.where(n_in, fx.gather(1, ni).squeeze(1), z)
        b_st = torch.where(b_in, st.gather(1, bi).squeeze(1), z)
        b_fx = torch.where(b_in, fx.gather(1, bi).squeeze(1), z)

        push = (a >= 1) & (a <= 4)
        move = a >= 5
        can_push = push & ((n_st == 3) | (n_st == 4)) & ((b_st == 1) | (b_st == 2))
        # ``_push`` falls back to ``_move`` when there is no box to push; ``_move`` steps onto floor
        # or an empty target only
        walk = (move | (push & ~can_push)) & ((n_st == 1) | (n_st == 2))

        stepped = can_push | walk
        pi = (pr * W + pc).unsqueeze(1)
        # the cell the player leaves reverts to room_fixed, and its tile id IS that value: 0 wall,
        # 1 floor, 2 empty target are the same three numbers in both alphabets
        left = fx.gather(1, pi).squeeze(1)
        enter = torch.where(n_fx == 2, torch.full_like(pr, 6), torch.full_like(pr, 5))
        box = torch.where(b_fx == 2, torch.full_like(pr, 3), torch.full_like(pr, 4))

        out = tile
        out = out.scatter(1, bi, torch.where(can_push, box, out.gather(1, bi).squeeze(1)).unsqueeze(1))
        out = out.scatter(1, ni, torch.where(stepped, enter, out.gather(1, ni).squeeze(1)).unsqueeze(1))
        out = out.scatter(1, pi, torch.where(stepped, left, out.gather(1, pi).squeeze(1)).unsqueeze(1))
        s.copy_(out.to(torch.float32))

    @torch.no_grad()
    def step(self, action) -> TensorDict:
        """Advance every environment one step. ``action`` is ``(B, 1)``, floored into ``[0, 9)``.

        STATEFUL: it writes ``env.state``. Returns a :data:`~stable_envs.env.StepResult` carrying
        ``"state"`` AND NOTHING ELSE. Termination and the reward are not applied and not reported:
        the reference computes the transition regardless and reports both as flags beside it, so an
        env that froze or reset itself on the last box would be simulating something else, and a
        fabricated zero reward would read as a measured one (contract §5). Unlike every other
        steppable env in this repo the returned state is the WHOLE dynamical state -- no hidden
        velocity, no carried object, no RNG -- so a stored trajectory determines its own continuation
        exactly, and ``transition`` needs no hidden field to be pure.
        """
        self._act.copy_(
            torch.as_tensor(action, device=self.device, dtype=torch.float32).reshape(self.B, self.action_dim)
        )
        self._advance()
        return self._step_result(self._step_state())

    @torch.no_grad()
    def transition(self, state: TensorDict, action) -> TensorDict:
        """``(state, action) -> next_state``. FUNCTIONAL: the env's own buffers are not touched.

        Bit-identical to ``step`` on the same device for the same state by CONSTRUCTION: both call
        ``_advance_into``, which is the whole transition, over buffers the caller names.
        """
        rows = self.pack(state).clone()
        act = torch.as_tensor(action, device=self.device, dtype=torch.float32).reshape(-1, self.action_dim)
        self._advance_into(rows, act)
        return self.unpack(rows)

    def _close(self) -> None:
        """Drop what this INSTANCE holds. ``Env.close`` calls this once and is idempotent.

        The 16x16 tile art (``_Atlas``) is shared by every instance and is not released. What an
        instance owns is the sampled state pool, the default-style tensor and the per-palette RGB
        cache, all of them rebuildable and all of them device memory a closed env has no use for.
        """
        self._pool = None
        self._pool_has = None
        self._default_t = None
        self._rgb_cache.clear()

    # --- states -----------------------------------------------------------------------------------

    def sample_states(self, batch: int, rng: np.random.Generator | None = None) -> np.ndarray:
        """Rollout states from the official env, STRATIFIED so all seven tiles occur in every batch.

        Uniform draws from the pool are not enough and the reason is measured rather than suspected:
        under random actions a box sits on a target in **7.0%** of states and the player stands on one
        in **9.4%**, so **221 of 500** 16-state batches were missing at least one tile id. A missing tile means the knob that colours it cannot
        move a pixel, and ``check_colors_apply_exactly`` would then pass or fail on the draw rather
        than on the renderer. Every state here is a real one the env reached; only WHICH of them are
        selected is arranged.
        """
        rng = rng or self.rng
        if self._pool is None:
            self._build_pool(512)
        pool, has = self._pool, self._pool_has
        idx = rng.choice(len(pool), batch, replace=batch > len(pool))
        if batch >= N_TILE:
            for _ in range(N_TILE + 1):
                missing = [t for t in range(N_TILE) if not has[idx, t].any()]
                if not missing:
                    break
                for t in missing:
                    cand = np.flatnonzero(has[:, t])
                    idx[rng.integers(0, batch)] = cand[rng.integers(0, len(cand))]
        return pool[idx].astype(np.float32)

    def _build_pool(self, n: int) -> None:
        """Random rollouts of the official env, as tile grids, with a per-state tile census.

        ``generate_room`` draws from the two GLOBAL random number generators -- ``random`` for the
        reverse-play walk and ``np.random`` for the box placements -- and takes no seed, so a pool
        built without seeding them is a different pool in every process. That is not a cosmetic
        difference: ``sample_states(rng=)`` is supposed to be reproducible from its seed alone, and it
        was not (caught by the cross-process check, two different digests for the same seed). Both are
        seeded per episode here and both are restored afterwards, so building a pool does not move a
        generator the caller is using.
        """
        u = self._official()
        py_state, np_state = random.getstate(), np.random.get_state()
        out = []
        ep = 0
        while len(out) < n:
            random.seed(ep)
            np.random.seed(ep)
            u.reset()
            r = np.random.default_rng(ep)
            for _ in range(24):
                out.append(self._tiles_of(u).reshape(-1))
                if len(out) >= n:
                    break
                # the official dispatch, without the render: ``step`` re-decodes seven PNGs on every
                # call (5.08 ms measured) to produce an observation nothing here reads
                self.reference_step(u, [r.integers(0, N_ACTIONS)])
            ep += 1
        random.setstate(py_state)
        np.random.set_state(np_state)
        self._pool = np.stack(out).astype(np.float32)
        self._pool_has = np.stack([(self._pool == t).any(1) for t in range(N_TILE)], 1)

    # --- reference bridge ---------------------------------------------------------------------------

    @classmethod
    def _official(cls):
        """``SokobanEnv`` directly, not through ``gym.make``.

        ``gym.make`` on the legacy ``gym`` wraps the env in ``TimeLimit``/``OrderEnforcing``/
        ``PassiveEnvChecker``, all of which call ``reset(seed=...)`` -- a signature
        ``SokobanEnv.reset(second_player=..., render_mode=...)`` does not have. Constructing the class
        is both the shorter path and the one that does not depend on which wrappers the shim installs.
        """
        from gym_sokoban.envs.sokoban_env import SokobanEnv

        return SokobanEnv(dim_room=(cls.ROOM_H, cls.ROOM_W), num_boxes=cls.NUM_BOXES, max_steps=cls.MAX_STEPS)

    @staticmethod
    def _tiles_of(u) -> np.ndarray:
        """``room_to_rgb``'s own join: ``room_state``, with id 5 rewritten to 6 on a target."""
        t = np.array(u.room_state, np.int64).copy()
        t[(np.array(u.room_state) == 5) & (np.array(u.room_fixed) == 2)] = 6
        return t

    @classmethod
    def reference_env(cls, size: int | None = None):
        if size is not None and int(size) != cls.default_size:
            raise ValueError(
                f"the official renderer draws 16 px tiles and nothing else, so there is no reference "
                f"frame at size {size}; parity is measured at {cls.default_size}"
            )
        return cls._official()

    @classmethod
    def reference_set_state(cls, u, st) -> None:
        """Write a tile grid back as the reference's own ``(room_state, room_fixed, player_position)``."""
        tile = np.round(np.asarray(st, np.float64)).astype(np.int64).reshape(cls.ROOM_H, cls.ROOM_W)
        tile %= N_TILE
        u.room_state = np.asarray(ROOM_STATE_OF, np.int64)[tile]
        u.room_fixed = np.asarray(ROOM_FIXED_OF, np.int64)[tile]
        where = np.argwhere(u.room_state == 5)
        u.player_position = where[0] if len(where) else np.array([0, 0])
        u.num_env_steps = 0
        u.boxes_on_target = 0

    @classmethod
    def reference_render(cls, env, states) -> np.ndarray:
        """Official frames, through the real ``room_to_rgb``, with the round-trip asserted.

        The assertion is the whole point of splitting the tile id back into two grids: if the reference
        did not end up at the requested scene, every parity number computed from it would be comparing
        two different pictures, and the failure would present as a renderer bug.
        """
        out = []
        for st in np.asarray(states):
            cls.reference_set_state(env, st)
            want = np.round(np.asarray(st, np.float64)).astype(np.int64) % N_TILE
            got = cls._tiles_of(env).reshape(-1)
            if not np.array_equal(got, want):
                bad = int((got != want).sum())
                raise AssertionError(
                    f"Sokoban: the reference did not reach the requested state ({bad} cells differ); "
                    f"parity measured against this frame would compare two scenes"
                )
            out.append(np.asarray(env.render(mode="rgb_array")).copy())
        return np.stack(out)

    # --- step bridge --------------------------------------------------------------------------------

    @classmethod
    def reference_sim_state(cls, ref) -> np.ndarray:
        return cls._tiles_of(ref).reshape(-1).astype(np.float64)

    @classmethod
    def reference_step(cls, ref, a) -> None:
        """``SokobanEnv.step``'s dispatch, without the reward and without the render.

        ``step`` renders an observation on every call, which the official renderer does by re-decoding
        seven PNGs -- 5.08 ms, measured -- and it also counts steps toward ``max_steps``. Neither
        touches the transition, and paying for a hundred renders per episode to compare a decision
        table would make the check something nobody runs. The dispatch below is the reference's own,
        verbatim.
        """
        act = int(min(max(int(np.floor(float(np.asarray(a).reshape(-1)[0]))), 0), N_ACTIONS - 1))
        if act == 0:
            return
        if act < 5:
            ref._push(act)
        else:
            ref._move(act)

    @classmethod
    def step_reference_reset(cls, ref, seed: int) -> np.ndarray:
        """Generate a fresh room. ``generate_room`` takes no seed and draws from BOTH global
        generators -- ``random`` for the reverse-play walk, ``np.random`` for the box placements -- so
        both are seeded, or the episode this check compares is not the one the seed names."""
        random.seed(int(seed))
        np.random.seed(int(seed))
        ref.reset()
        return cls.reference_sim_state(ref)
