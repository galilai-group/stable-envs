"""Sokoban / Boxoban: a 7-entry tile atlas, a gather, and a transition table that is exactly checkable.

Reference: ``gym-sokoban`` 0.0.6 (which installs against the legacy ``gym``, not ``gymnasium``).
``render_utils.room_to_rgb`` is the whole renderer -- it blits one of seven 16x16 PNGs per grid cell --
so this env belongs on the same path as MiniGrid: precompute the tiles and render by gathering from
them. Exactness is then structural rather than measured, and the measurement says so:

  * the atlas is **7 x 16 x 16 x 3 uint8 = 5,376 bytes**, and a pure gather from it reproduces
    ``render(mode='rgb_array')`` with **max absolute pixel difference 0** over 120 frames spanning 12
    generated rooms;
  * the whole atlas uses **10 distinct colours**, so a recolouring variation is a 10-entry palette
    applied to a label map with no filtering at all -- ``palette[label]`` IS the tile, and an RGB knob
    therefore puts its literal colour in the frame rather than an interpolation of it. ``_Atlas``
    asserts that reconstruction against the official PNGs at the default palette, so a wrong constant
    cannot survive construction;
  * the official CPU renderer runs at **197 frames/s** (5.08 ms a frame) because it re-reads and
    re-decodes all seven PNGs on **every single call**.

THE STATE IS ONE INDEX PER CELL, AND THAT IS NOT THE ENV'S OWN LAYOUT.
``room_to_rgb`` picks its tile from ``room_state`` after rewriting id 5 to 6 wherever
``room_structure == 2`` -- a player standing on a target -- so the drawn tile is a function of TWO
grids, ``room_state`` and ``room_fixed``. Storing both would be twice the state and, worse, would carry
dimensions that cannot change the picture (``room_fixed`` is invisible under a box). The 7-value tile
id is the join, and it is invertible: measured over 1,200 cells x 120 real states, the only
``(room_state, room_fixed)`` pairs that occur are the seven

    (0,0) wall   (1,1) floor   (2,2) empty target   (3,2) box on target
    (4,1) box    (5,1) player  (5,2) player on target

so ``room_state`` and ``room_fixed`` are both recovered from the tile id exactly (asserted every time
the reference is driven, in ``reference_render``). One index per cell is therefore minimal AND
sufficient: every dimension changes 256 pixels, and nothing else is needed to render or to step.

Physics
-------

``step`` is a batched GPU port of ``SokobanEnv._push`` / ``_move``, and this is the second family in
the repo -- after MiniGrid -- where the simulator's claim is as strong as the renderer's. The reason is
structural: the transition is a finite decision table over a finite alphabet (nine actions: no-op, four
pushes, four moves), so a port either agrees with the reference on every ``(state, action)`` pair or it
has a bug. There is no chaos to hide behind and no tolerance to negotiate, so ``exact_frac`` is the
only statistic worth quoting.

Measured by ENUMERATION rather than by rollout, because a random rollout is a weak test of a decision
table: **all 9 actions from each of 1,024 states, 9,216
transitions, 921,600 cells, 0 mismatched**, plus 16 x 100 uniform-random steps at ``exact_frac 1.0``.
The enumeration pool is drawn from real rollouts and is stratified so that every outcome occurs -- 131
pushes onto a target, 9 off one, 354 plain pushes, 3,947 walks and 4,775 blocked moves. A rollout that
never lands a box on a target never exercises the ``box_type = 3`` branch, which is exactly the branch
a decision table gets wrong.

One boundary case is decided here rather than in the reference, and it is unreachable in a real room.
``_move`` indexes ``room_state`` with no bounds check at all, so a player one cell outside the grid
would wrap under numpy's negative indexing or raise; ``_push`` bounds-checks only the FAR edge
(``new_box_position >= shape``) and, when it trips, returns WITHOUT falling back to ``_move``. This
port instead treats any cell outside the grid as a wall, so a push whose box would land off the edge
falls through to the move, which then finds a wall in front of it and does nothing. The two agree on
every reachable state: every room ``generate_room`` produces is surrounded by a wall ring, so the cell
the player would step into at the border is a wall and neither branch writes anything.

The dependency is HARD, and this module says so at import
---------------------------------------------------------

There is no degraded mode: the seven PNGs are the renderer, and ``sample_states`` rolls the official
env out because a room is generated by a reverse-play search with no closed form. So the whole runtime
is probed at import -- ``imageio``, the seven files themselves, and ``SokobanEnv`` constructing -- and
``ImportError`` is raised if any of it is missing, which is what makes the env cleanly ABSENT on a
machine without ``gym-sokoban`` rather than present and failing. Measured: registering anyway turned
one missing package into **15 test failures**, every one raised inside a fixture where an absent env is
indistinguishable from a broken one.

Not ported: ``room_to_tiny_world_rgb`` (a second, flat-colour atlas at 1 px per cell) and room
GENERATION. ``room_utils.generate_room`` runs a reverse-play search and is where Sokoban's CPU time
actually goes, but it is a level generator rather than a transition, and this repo ports renderers and
transitions. Boxoban shares both the renderer and the transition and changes only how rooms are
generated, so it is covered by the same atlas and the same ``step``.
"""

