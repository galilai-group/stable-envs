"""MiniHack / NetHack — the family where "store states, not frames" pays the most and costs the least.

Reference: ``minihack.tiles.glyph_mapper.GlyphMapper``, which is what MiniHack itself calls to build the
``pixel`` observation. It is not a rasterizer. It is

    frame[r*16:(r+1)*16, c*16:(c+1)*16] = tiles[glyph2tile[glyphs[r, c]]]

and nothing else: ``_glyph_to_rgb`` is a double loop over the glyph array concatenating fixed 16x16 RGB
tiles. So the frame is a gather from a finite atlas indexed by the 21x79 glyph grid, and there is no
sub-pixel geometry, no blending and no float arithmetic anywhere in the path. Parity is therefore not a
tuning exercise, and it is measured, not asserted: against ``GlyphMapper`` on 64 sampled states,
**100% of all pixels exact, mean |diff| 0.000, max |diff| 0**. Rebuilding the observation from
``glyphs`` alone likewise reproduced it bit for bit on 40/40 steps of ``MiniHack-Room-5x5-v0``.

The ratio is the largest in the repo. The glyph grid is 21x79 int16 = 3318 bytes; the frame it
determines is 336x1264x3 = 1,274,112 bytes. **384x** for a dataset that stores glyphs as int16, or
**192x** against this env's float32 state vector, which is the honest number to quote when the state is
carried as ``(B, 1659)`` float32 like every other env here.

Measured throughput of the gather on one H200: **246,056 frames/s at batch 4096** against **178
frames/s** for ``GlyphMapper.to_rgb`` (5.62 ms/frame, a Python double loop over ``np.concatenate``) —
**1391x** — saturating at 313 GB/s of frame output, which is where a pure gather should stop.

What this module is and is not:

  * It is a **renderer**, not a simulator. NetHack's dynamics live in a C binary and stay there. That is
    the case this repo targets: the NetHack corpora that exist are large because they store frames, and
    the glyph grid that generates those frames is 384x smaller.
  * The glyph grid determines the ``pixel`` observation completely, but it is not NetHack's state. It
    does not carry the message line, the status line, inventory, or anything the ``tty_*``
    observations hold — none of which appear in the pixel observation either, so nothing that is
    rendered is missing.
  * The atlas and the glyph->tile table are **embedded** in this module (zlib+base64, 68 kB and 2.2 kB)
    rather than loaded from an installed ``minihack``. Requiring a NetHack build in order to re-render a
    stored state dataset would defeat the point; the blobs come straight out of ``minihack.tiles`` and
    are byte-identical to it.

Two measured details that shaped the code:

  * **``glyph2tile`` is far from injective** — 5976 glyph ids map onto 1023 distinct tiles. The
    conformance suite calls a state dimension dead if a +25 perturbation leaves the frame unchanged, so
    every glyph ``sample_states`` can emit was checked to satisfy ``tile(g) != tile(g+25)``; the
    accepted set is the ``G_*`` constants below, generated by
    the frozen measurement record.
  * **The 16 px tile size is the only one the official renderer has.** ``render(size=t)`` for other ``t``
    resamples the atlas by nearest neighbour, which is a convenience, not a claim: only ``size=16`` is
    bit-exact against MiniHack.
"""

