def _unpack(b64: str, dtype, shape) -> np.ndarray:
    return np.frombuffer(zlib.decompress(base64.b64decode(b64)), dtype=dtype).reshape(shape)


class _Assets:
    """Atlas and glyph->tile table, decoded once per device.

    Decoding is ~1 MB of zlib and the result is read-only, so it is cached per device rather than
    rebuilt per environment: a benchmark that constructs a few hundred envs should not pay for it a few
    hundred times, and every env holds the same tensor.
    """

    _cache: dict = {}

    @classmethod
    def get(cls, device: torch.device):
        key = str(device)
        if key not in cls._cache:
            atlas = torch.as_tensor(_unpack(_ATLAS_B64, np.uint8, (N_TILE, TILE_PX, TILE_PX, 3)).copy(), device=device)
            g2t = torch.as_tensor(_unpack(_GLYPH2TILE_B64, np.int16, (N_GLYPH,)).astype(np.int64), device=device)
            cls._cache[key] = (atlas, g2t)
        return cls._cache[key]


@register
class MiniHack(Env):
    """NetHack's 21x79 glyph grid, rendered as a batched atlas gather. State = the glyph ids."""

    family = "minihack"
    domain = "minihack"

    name = "minihack"
    state_dim = GRID_H * GRID_W
    state_names = tuple(f"glyph_r{r:02d}c{c:02d}" for r in range(GRID_H) for c in range(GRID_W))

    @property
    def frame_shape(self) -> tuple[int, int]:
        """``(H, W)`` of a frame: the 21x79 glyph grid at ``size`` px per tile, so 336x1264 at the
        default 16. ``Env.frame_spec`` defaults to a SQUARE frame and this one is nowhere near
        square; without this the spec would describe a 16x16 buffer. ``size`` is the TILE size for
        this env, which is what ``default_size = TILE_PX`` says."""
        return GRID_H * int(self.size), GRID_W * int(self.size)

    #: tile edge in pixels, NOT the output resolution: the frame is (21*size, 79*size, 3)
    default_size = TILE_PX
    reference_id = "minihack.tiles.glyph_mapper.GlyphMapper"

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self.atlas, self.glyph2tile = _Assets.get(self.device)

    # variation

    def make_variation_space(self) -> Dict:
        """Global recolourings, and deliberately nothing else.

        The atlas is fixed bitmap art shipped with NetHack, not procedurally drawn tiles, so there is no
        honest per-object knob to expose: MiniGrid can vary a door's colour because MiniGrid *draws* the
        door, whereas here a door is 768 bytes of someone's pixel art. Inventing a recolouring per glyph
        class would advertise a semantics the reference does not have. What is offered instead is two
        knobs that apply to the atlas as a whole, both of which are the identity at their defaults:

          ``background_color``  every pure-black pixel becomes this colour. Black is the tile background
                                throughout the set (the solid-rock glyph is entirely black), so this is
                                the closest thing to a real background in a tileset that has none.
          ``channel_gain``      per-channel multiplier, applied as ``round(x * g)`` clamped to 0-255.
                                At ``g = 1`` this is exactly the identity in float32, so the default
                                still reproduces MiniHack byte for byte.

        When one appearance is shared by the whole batch, both are baked into a recoloured copy of the
        atlas rather than applied to the frame, so the hot path stays a single gather; a 831 kB atlas
        is cheaper to touch than a batch of 1.27 MB frames. When the batch carries one appearance per
        environment they are applied to the frame instead, because B recoloured atlases is the more
        expensive of the two the moment B exceeds a couple of frames' worth of work. The two paths
        compute the same thing: the recolouring is a per-pixel function of the pixel, so applying it
        before or after the gather is the same arithmetic.
        """
        return Dict(
            {
                "background_color": RGBBox(init_value=(0, 0, 0)),
                "channel_gain": Box(low=0.0, high=2.0, shape=(3,), dtype=np.float32, init_value=[1.0, 1.0, 1.0]),
            }
        )

    def _base_atlas(self, size: int) -> torch.Tensor:
        """The shipped atlas, resampled to ``size`` px per tile and otherwise untouched."""
        if size == TILE_PX:
            return self.atlas
        # nearest neighbour on tile-local coordinates. Only size == TILE_PX is bit-exact against
        # MiniHack, which has exactly one tile size; other sizes are a convenience for training at
        # a cheaper resolution and are documented as such.
        ix = (
            ((torch.arange(size, device=self.device, dtype=torch.float32) + 0.5) * TILE_PX / size)
            .long()
            .clamp_(0, TILE_PX - 1)
        )
        return self.atlas[:, ix][:, :, ix]

    def _atlas_for(self, bg: np.ndarray, gain: np.ndarray, size: int) -> torch.Tensor:
        """The atlas one shared appearance gathers from: resampled to ``size`` px, then recoloured."""
        atlas = self._base_atlas(size)
        if bg.any():
            atlas = atlas.clone()
            black = (atlas == 0).all(-1)
            atlas[black] = torch.as_tensor(bg, device=self.device, dtype=torch.uint8)
        if not np.array_equal(gain, np.ones(3, np.float32)):
            g = torch.as_tensor(gain, device=self.device, dtype=torch.float32)
            atlas = (atlas.float() * g).round_().clamp_(0, 255).to(torch.uint8)
        return atlas

    def _recolour_frames(self, img: torch.Tensor, sty, out=None) -> torch.Tensor:
        """Per-environment ``background_color`` and ``channel_gain``, applied to the frames.

        Chunked over the batch: the float32 intermediate is 4x the frame, and a MiniHack frame is
        1.27 MB, so a whole 4096-environment batch would be 21 GB in one allocation.
        """
        n = img.shape[0]
        bg = sty["background_color"].to(torch.uint8).view(n, 1, 1, 3)
        gain = sty["channel_gain"].view(n, 1, 1, 3)
        if out is None:
            out = torch.empty_like(img)
        step = max(1, int((256 << 20) // max(1, img[0].numel() * 4)))
        for b0 in range(0, n, step):
            b1 = min(n, b0 + step)
            x = img[b0:b1]
            x = torch.where((x == 0).all(-1, keepdim=True), bg[b0:b1], x)
            out[b0:b1] = (x.float() * gain[b0:b1]).round_().clamp_(0, 255).to(torch.uint8)
        return out

    # render

    @torch.no_grad()
    def render(
        self,
        states=None,
        size: int | None = None,
        supersample: int | None = None,
        variation: dict | None = None,
        style=None,
        out=None,
    ) -> torch.Tensor:
        """``(...,1659)`` glyph ids -> ``(...,21*size,79*size,3)`` uint8 on device.

        There is no ``scene()``: a Scene2D describes vector primitives to be rasterised, and this frame
        is not rasterised at all. Forcing 1659 textured quads through a polygon IR would re-derive, per
        frame, an image the tileset already holds.
        """
        s = self._state if states is None else torch.as_tensor(states, device=self.device, dtype=torch.float32)
        lead = tuple(s.shape[:-1])
        s = s.reshape(-1, self.state_dim)
        n = s.shape[0]
        t = int(size or self.size)
        if supersample not in (None, 1):
            raise ValueError(
                f"MiniHack.render: supersample={supersample} is meaningless here. Supersampling exists "
                f"to estimate sub-pixel coverage of analytic geometry; this frame is an exact gather "
                f"from a bitmap atlas, so there is no coverage to estimate and averaging copies of the "
                f"same tile would only blur the reference."
            )

        sty = self.resolve_style(style, variation, batch=n)
        # asked on the device and read back as one value: copying the whole style tensor to the host
        # to compare it there is pointless traffic for a one-bit answer
        v = sty.values
        shared = v.shape[0] == 1 or bool((v == v[:1]).all())
        glyph = s.round().long().clamp_(0, N_GLYPH - 1).view(n, GRID_H, GRID_W)
        if shared:
            v0 = self.variation_space.unpack(v[0].detach().cpu().numpy())
            atlas = self._atlas_for(
                np.asarray(v0["background_color"], np.float64).astype(np.int64),
                np.asarray(v0["channel_gain"], np.float32),
                t,
            )
        else:
            atlas = self._base_atlas(t)
        tiles = atlas[self.glyph2tile[glyph]]  # (n,H,W,t,t,3)
        if out is not None and shared:
            # write straight into the caller's buffer: out.view(...) is contiguous and the permuted
            # gather is a strided view, so copy_ is the only traffic and nothing is allocated.
            out.view(n, GRID_H, t, GRID_W, t, 3).copy_(tiles.permute(0, 1, 3, 2, 4, 5))
            img = out.view(n, GRID_H * t, GRID_W * t, 3)
        else:
            img = tiles.permute(0, 1, 3, 2, 4, 5).reshape(n, GRID_H * t, GRID_W * t, 3)
            if not shared:
                img = self._recolour_frames(img, sty, None if out is None else out.view(n, GRID_H * t, GRID_W * t, 3))
        return img.view(*lead, *img.shape[1:]) if lead else img

    # states

    def sample_states(self, batch: int, rng: np.random.Generator | None = None) -> np.ndarray:
        """Random MiniHack-style rooms: solid rock, a walled room, features, monsters and objects.

        These are synthetic layouts over a glyph vocabulary read out of ``nle`` (see the module
        docstring), not recorded rollouts. That is sufficient and is arguably stronger: ``to_rgb``
        depends on nothing but the glyph ids, so a layout the sampler invents exercises the renderer
        exactly as a real one does, and the vocabulary spans dungeon features, monsters, pets and
        objects rather than the handful a single level happens to contain.
        """
        rng = rng or self.rng
        g = np.full((batch, GRID_H, GRID_W), G_STONE, dtype=np.float32)
        for b in range(batch):
            h = int(rng.integers(4, 10))
            w = int(rng.integers(8, 24))
            r0 = int(rng.integers(1, GRID_H - h - 1))
            c0 = int(rng.integers(1, GRID_W - w - 1))
            r1, c1 = r0 + h, c0 + w
            g[b, r0 : r1 + 1, c0] = G_VWALL
            g[b, r0 : r1 + 1, c1] = G_VWALL
            g[b, r0, c0 : c1 + 1] = G_HWALL
            g[b, r1, c0 : c1 + 1] = G_HWALL
            g[b, r0, c0], g[b, r0, c1] = G_TLCORN, G_TRCORN
            g[b, r1, c0], g[b, r1, c1] = G_BLCORN, G_BRCORN
            g[b, r0 + 1 : r1, c0 + 1 : c1] = G_ROOM
            # a door on one of the four walls
            if rng.random() < 0.5:
                g[b, int(rng.integers(r0 + 1, r1)), c0 if rng.random() < 0.5 else c1] = G_DOOR_VERT
            else:
                g[b, r0 if rng.random() < 0.5 else r1, int(rng.integers(c0 + 1, c1))] = G_DOOR_HORIZ
            free = [(r, c) for r in range(r0 + 1, r1) for c in range(c0 + 1, c1)]
            k = min(len(free), int(rng.integers(4, 12)))
            pool = _FEATURES + _MONSTERS + _OBJECTS
            for i in rng.choice(len(free), size=k, replace=False):
                r, c = free[int(i)]
                g[b, r, c] = pool[int(rng.integers(len(pool)))]
            # a corridor leaving the room, so the state is not a single connected rectangle
            rr = int(rng.integers(r0 + 1, r1))
            for c in range(0, c0):
                g[b, rr, c] = G_CORR
        return g.reshape(batch, self.state_dim)

    # reference bridge

    @staticmethod
    def reference_env(size: int = TILE_PX):
        """MiniHack's own glyph->pixel mapper, which is the official renderer for the pixel obs.

        ``minihack.base`` builds the ``pixel`` observation by calling exactly this object, so comparing
        against it is comparing against the shipped renderer and not against a re-derivation of it. It
        needs no level, no seed and no game process: the mapping is a function of the glyph array, which
        is the property this env exists to exploit.
        """
        if int(size) != TILE_PX:
            raise ValueError(
                f"the official MiniHack renderer has exactly one tile size ({TILE_PX} px); there is no "
                f"reference to compare a {size} px render against"
            )
        from minihack.tiles.glyph_mapper import GlyphMapper

        return GlyphMapper()

    @staticmethod
    def reference_render(env, states) -> np.ndarray:
        """Official frames for the given glyph grids."""
        g = np.asarray(states, dtype=np.float64).round().astype(np.int32).reshape(-1, GRID_H, GRID_W)
        return np.stack([np.asarray(env.to_rgb(grid), dtype=np.uint8) for grid in g])
