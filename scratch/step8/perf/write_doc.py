def fmt(x, n=2, dash="—"):
    if x is None:
        return dash
    if isinstance(x, float):
        if x >= 1000:
            return f"{x:,.0f}"
        return f"{x:.{n}f}"
    return str(x)


def table(head: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |",
           "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def tier_table(doc: dict) -> list[str]:
    rows = []
    for r in doc["rows"]:
        c, g = r["cpu"], r["gpu"]
        rows.append([
            f"`{r['swm_id']}`",
            f"`{r['primary_cell']}`" if r["primary_cell"] else "—",
            r["backend_class"] or "—",
            f"`{c['tier']}`", c["status"],
            ", ".join(f"`{f}`" for f in c["flags"]) or "—",
            f"`{g['tier']}`", g["status"],
            ", ".join(f"`{f}`" for f in g["flags"]) or "—",
        ])
    return table(["SWM id", "primary cell", "class", "CPU tier", "CPU status", "CPU flags",
                  "GPU tier", "GPU status", "GPU flags"], rows)


def numbers_table(doc: dict, dev: str) -> list[str]:
    rows = []
    for r in doc["rows"]:
        e = r[dev]
        if e["status"] != "MEASURED":
            continue
        n, p = e["numbers"], e["provenance"]
        common = [f"`{r['swm_id']}`", f"`{e['tier']}`"]
        prov = f"{p.get('host') or '—'} / {p.get('job') or '—'}"
        if dev == "cpu":
            rows.append(common + [fmt(n.get("S_cpu")), fmt(n.get("cores_cpu"), 3),
                                  fmt(n.get("fps_best")), fmt(n.get("official_fps")),
                                  fmt(n.get("decode_fps_per_core")), fmt(n.get("best_batch"), 0),
                                  e["reference"]["label"], prov])
        else:
            rows.append(common + [fmt(n.get("R")), fmt(n.get("cores")),
                                  fmt(n.get("fps_1")), fmt(n.get("fps_best")),
                                  fmt(n.get("batch_scales_ratio")),
                                  fmt(n.get("no_large_batch_regression_ratio"), 3),
                                  fmt(n.get("host_bound_cpu_frac"), 3),
                                  e["reference"]["label"], prov])
    if dev == "cpu":
        head = ["SWM id", "CPU tier", "S_cpu", "cores_cpu", "our f/s", "official f/s",
                "1-core decode f/s", "batch", "reference", "host / job"]
    else:
        head = ["SWM id", "GPU tier", "R", "cores", "fps(1)", "fps(best)", "BATCH_SCALES",
                "NO_LARGE_BATCH_REGR.", "cpu_frac", "reference", "host / job"]
    return table(head, rows)


def sources_table(doc: dict) -> list[str]:
    return table(["artifact", "sha256", "what it supplies"],
                 [[f"`{s['path']}`", f"`{s['sha256'][:16]}…`", "; ".join(s["roles"])[:180]]
                  for s in doc["sources"]])


def unmeasured_table(doc: dict) -> list[str]:
    rows = []
    for r in doc["rows"]:
        for dev in ("cpu", "gpu"):
            e = r[dev]
            if e["status"] == "MEASURED":
                continue
            b = e.get("blocked") or {}
            rows.append([f"`{r['swm_id']}`", dev.upper(), f"`{e['tier']}`", e["status"],
                         (b.get("kind") or "—"),
                         ((b.get("reason") or e.get("why_this_source") or "—")[:300])])
    return table(["SWM id", "device", "tier", "status", "kind", "why, from the record"], rows)


def lance_rows(l: dict) -> dict:
    return {r["env"]: r for r in l["rows"]}


