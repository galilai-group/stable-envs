"""Generate the ONE authoritative support matrix for all 42 SWM ids, from committed artifacts.

    python scratch/step8/report.py

writes ``docs/research/step8_support_matrix.md`` and ``examples/results/step8/support_matrix.json``.

Plan section 22 asks for the table to be generated "from committed artifacts, not hand-maintained
prose", and the reason is the one Step 3 and Step 4 both gave for computing their universes: a
hand-maintained table drifts from the evidence the moment either moves, and the drift is SILENT --
a row quietly dropped is indistinguishable, in the table, from a row that passed.

So there is exactly one editorial decision in this file -- ``STATUS_RULES`` below, which maps a
measured fact to one of the five words plan section 3 defines -- and everything else is read out of a
committed file and cited by path. The five words are kept apart deliberately:

    PASS                     the claim holds and there is evidence for it
    UNSUPPORTED_BY_DESIGN    the capability is absent ON PURPOSE and the env says so
    UNMEASURED               nobody measured it; this is an absence of evidence, not a failure
    DOCUMENTED_LIMITATION    known, measured, bounded, and the library stays truthful with it
    UPSTREAM_FINDING         the defect belongs to SWM or a dependency, not here

Collapsing any of those into a generic FAIL is the specific thing the plan forbids, because the four
non-PASS words carry different obligations: one is closed, one is work, one is a record, one is
somebody else's.

This is a JOIN, not a measurement. It never constructs an env, never renders, and never re-measures.
The coordinator regenerates it as other workstreams merge, and rows will change as they do -- which
is the point of generating it rather than writing it.
"""
from __future__ import annotations

import argparse
import json
import subprocess
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
S7 = ROOT / "examples" / "results" / "step7"
S8 = ROOT / "examples" / "results" / "step8" / "certification"

#: The committed join at the Step-8 baseline: 42 rows, 40 pixel-producing, 2 symbolic, with
#: ``integration_head_verified``. Regenerated by the coordinator as workstreams merge; this file
#: reads whichever version is committed rather than carrying a copy.
COVERAGE_MATRIX = S7 / "closure2" / "coverage_matrix.json"

#: The five words, weakest claim last. Used to order the summary blocks, never to rank a row.
STATUSES = ("PASS", "DOCUMENTED_LIMITATION", "UPSTREAM_FINDING", "UNSUPPORTED_BY_DESIGN", "UNMEASURED")

#: THE ONE EDITORIAL TABLE. Each entry maps a verdict string that appears in a committed artifact to
#: the plan-section-3 word it means. A verdict not listed here is reported verbatim with a "?" marker
#: rather than guessed into a bucket -- an unrecognised verdict is a signal that an upstream artifact
#: changed shape, and silently bucketing it would hide exactly that.
STATUS_RULES = {
    "PASS": "PASS",
    "PARTIAL": "DOCUMENTED_LIMITATION",
    "REFUSED_BY_DESIGN": "UNSUPPORTED_BY_DESIGN",
    "BLOCKED": "UNMEASURED",
    "FAIL": "FAIL",                      # kept as itself: a real failure is not one of the five
    "-": "UNMEASURED",
    None: "UNMEASURED",
}

#: Tier strings that are an ABSENCE of measurement rather than a slow renderer, and the word each
#: means. Step 2's own distinction: "a dependency failure is not a regression".
TIER_STATUS = {
    "CPU_MISSING": "UNSUPPORTED_BY_DESIGN",   # qualified below: only when the env RAISES by design
    "CPU_UNMEASURED": "UNMEASURED",
    "GPU_UNMEASURED": "UNMEASURED",
    "unknown": "UNMEASURED",
}


def _sha() -> str:
    return subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT,
                          capture_output=True, text=True).stdout.strip()


def _load(p: Path, default=None):
    return json.loads(p.read_text()) if p.is_file() else default


def census_classes() -> dict:
    """``env -> (backend_class, backends)`` from the Step-8 census, through Step 3's own classifier.

    Imported rather than reimplemented: the class a row reports here and the class a tier was judged
    under must be the same function, or the table is quoting a number computed under a different rule
    from the one it prints beside it.
    """
    import sys
    sys.path.insert(0, str(ROOT / "scratch" / "step3"))
    sys.path.insert(0, str(ROOT))
    import importlib.util
    spec = importlib.util.spec_from_file_location("_c3", ROOT / "scratch" / "step3" / "certify.py")
    c3 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(c3)
    paths = sorted((ROOT / "scratch" / "census").glob("census_*.json"))
    decls = c3.read_censuses(paths)
    # The CLASS comes from ``read_censuses``, whose first-file-wins precedence is what guarantees a
    # previously classified cell keeps its class. The BACKENDS column reports the UNION over every
    # census instead, because precedence is the right rule for a verdict and the wrong one for an
    # inventory: CraftaxClassic's oldest declaration predates ``prng`` and printing an empty backend
    # list beside a cell that plainly has a renderer would be a worse answer than printing both.
    union: dict[str, set] = {}
    for one in paths:
        for e, d in c3.read_censuses([one]).items():
            union.setdefault(e, set()).update(d.get("backends") or [])
    return {e: (c3.backend_class(e, decls)[0], sorted(union.get(e, ()))) for e in decls}, decls


def _gate_a(row: dict, rejudged: dict | None = None) -> dict:
    g = row.get("gate_a") or {}
    records = [r for r in (rejudged or {}).get("records", [])
               if r["cell"] in (row.get("stable_envs_envs") or [])]
    if records:
        per_device = {}
        failures = set()
        for rec in records:
            judgment = rec["judgment"]
            verdict = judgment["gate_a"]
            # A historical CPU refusal is still an unsupported device, not a failed GPU claim.
            old = (g.get("per_device") or {}).get(rec["device"], {})
            if old.get("verdict") == "REFUSED_BY_DESIGN" and verdict == "BLOCKED":
                verdict = "REFUSED_BY_DESIGN"
            per_device.setdefault(rec["device"], []).append(verdict)
            failures.update(judgment["failures"])
        def aggregate(values):
            return next((v for v in ("FAIL", "BLOCKED", "PARTIAL", "PASS", "REFUSED_BY_DESIGN")
                         if v in values), "BLOCKED")
        devices = {dev: aggregate(values) for dev, values in per_device.items()}
        overall = aggregate(list(devices.values()))
        return {"status": STATUS_RULES[overall], "raw": overall,
                "per_device": {d: STATUS_RULES[v] for d, v in devices.items()},
                "failing_checks": sorted(failures),
                "source": "examples/results/step8/certification/gate_a_rejudged.json",
                "measurements": [{"cell": r["cell"], "device": r["device"],
                                  "source": r["source"], "source_sha256": r["source_sha256"],
                                  "blocked_checks": r["judgment"]["blocked"]} for r in records],
                "note": "Historical Step-7 measurements rejudged with the frozen Gate-A judge, "
                        "including family_specific checks. This is not a fresh Step-8 run; "
                        "unresolved historical protocol/reference issues remain visible."}
    devices = g.get("devices") or {}
    verdicts = {d: STATUS_RULES.get(v, f"?{v}") for d, v in devices.items()}
    overall = g.get("result") or ("FAIL" if "FAIL" in devices.values() else None)
    return {"status": STATUS_RULES.get(overall, f"?{overall}") if overall else "UNMEASURED",
            "raw": overall, "per_device": verdicts,
            "failing_checks": g.get("failing_checks") or [],
            "source": g.get("source"), "note": (g.get("note") or "")[:600]}


def _devices(row: dict) -> dict:
    """Which devices this cell honestly serves. A raise is a SUPPORTED answer, not a gap."""
    per = ((row.get("gate_a") or {}).get("per_device")) or {}
    out = {}
    for dev, d in per.items():
        v = d.get("verdict")
        out[dev] = {"verdict": v, "status": STATUS_RULES.get(v, f"?{v}"),
                    "why": (d.get("why") or "")[:400]}
    return out


def _tier(row: dict, key: str) -> dict:
    t = (row.get(key) or {})
    tier = t.get("tier")
    # MEASURED, not PASS, and the distinction is not pedantry: a tier is a GRADE, not a gate.
    # CPU_REGRESSION is a perfectly well-measured tier and labelling it "PASS" would read as "fast
    # enough", while labelling it "FAIL" would read as a defect. Neither is what a tier says. So the
    # tier string carries the grade and this column carries only whether a measurement exists.
    status = TIER_STATUS.get(tier, "MEASURED" if tier else "UNMEASURED")
    quals = t.get("qualifiers") or []
    if tier == "CPU_MISSING":
        # CPU_MISSING means two different things and the table must not merge them: an env that
        # RAISES on device="cpu" by design is honest and supported-by-design; an env that simply has
        # no CPU backend written yet is unmeasured work. The qualifier is what tells them apart.
        status = "UNSUPPORTED_BY_DESIGN" if "RAISES_BY_DESIGN" in quals else "UNMEASURED"
    return {"tier": tier or "unknown", "status": status, "qualifiers": quals,
            "source": t.get("source"), "note": ((t.get("detail") or {}).get("note") or "")[:400]}


def _variation(row: dict) -> dict:
    v = row.get("variation_space") or {}
    st = v.get("variation_map_status")
    dead = [x for x in (v.get("declared_out") or [])]
    return {"map_status": st or "unknown",
            "status": {"present": "PASS", "missing": "UNMEASURED"}.get(st, "UNMEASURED"),
            "n_swm_leaves": v.get("n_swm_leaves"),
            "declared_in": v.get("declared_in") or [], "unsupported_or_dead_leaves": dead,
            "note": (v.get("note") or "")[:400], "swm_status": v.get("swm_status")}


def _fidelity(row: dict) -> dict:
    f = row.get("fidelity") or {}
    vf = f.get("visual_fidelity") or {}
    return {"tier": f.get("tier"), "registered_default_coverage": f.get("registered_default_coverage"),
            "parity_interior_min": f.get("parity_interior_min"),
            "parity_all_exact_min": f.get("parity_all_exact_min"),
            "reference_versions": vf.get("reference_versions") or {},
            "measured_at": (vf.get("measured_at") or "")[:500]}


def limitations(env_names: list[str], row: dict, step8: dict) -> list[dict]:
    """Every recorded limitation that names this row, each with the artifact that measured it.

    Read out of this workstream's own Step-8 artifacts plus the row's own notes, so a limitation
    cannot be present in the tree and absent from the table.
    """
    out = []
    ds = (step8.get("downsample") or {}).get("cells") or {}
    for e in env_names:
        if e in ds and ds[e]["decision"].startswith("NOT ADDED"):
            out.append({"kind": "DOCUMENTED_LIMITATION", "what": "resolution consistency",
                        "detail": ds[e]["reason"][:300],
                        "artifact": "examples/results/step8/certification/downsample_provenance.json"})
    nv = step8.get("nvdiff") or {}
    if any(e == "PFRocketLanding" for e in env_names) and nv:
        out.append({"kind": nv.get("classification"), "what": "nvdiff x86 CPU sparse-stage one ULP",
                    "detail": "no shipped renderer draws through nvdiff on cpu; cuda bitwise "
                              "invariant at every width; the residual does not reproduce on the "
                              "baseline's own sweep host",
                    "artifact": "examples/results/step8/certification/nvdiff_ulp_classification.json"})
        out.append({"kind": "DOCUMENTED_LIMITATION", "what": "check_colors_apply_exactly",
                    "detail": "TinyRenderer's multiplicative law caps the shading factor at 0.993567, "
                              "so the exact requested RGB cannot appear for ANY correct "
                              "implementation, and does not appear in the official frames either. "
                              "OPEN escalation to Sami.",
                    "artifact": "examples/results/step8/certification/colour_check_decision.md"})
    note = ((row.get("gate_a") or {}).get("note") or "")
    if note and not out:
        out.append({"kind": "note", "what": "gate_a note", "detail": note[:300],
                    "artifact": (row.get("gate_a") or {}).get("source")})
    return out


def build() -> dict:
    matrix = _load(COVERAGE_MATRIX)
    if matrix is None:
        raise SystemExit(f"{COVERAGE_MATRIX} is missing: this table is a join over committed "
                         f"artifacts and there is nothing to join")
    classes, decls = census_classes()
    step8 = {"downsample": _load(S8 / "downsample_provenance.json"),
             "gate_a": _load(S8 / "gate_a_rejudged.json"),
             "nvdiff": _load(S8 / "nvdiff_ulp_classification.json"),
             "order": _load(S8 / "order_invariance_finding.json"),
             "corpora": _load(S8 / "corpus_index.json"),
             "census_diff": _load(S8 / "census_class_diff.json")}

    rows = []
    for r in matrix["rows"]:
        envs = r.get("stable_envs_envs") or []
        cls = sorted({classes.get(e, ("unknown", []))[0] for e in envs}) or ["n/a"]
        backends = sorted({b for e in envs for b in (classes.get(e, ("", []))[1] or [])})
        pixel = bool(r.get("pixel_producing"))
        rows.append({
            "swm_id": r["swm_id"],
            "stable_envs_cells": envs,
            "backend_class": cls[0] if len(cls) == 1 else "/".join(cls),
            "pixel_or_symbolic": "pixel" if pixel else "symbolic",
            "render_coverage": ("covered" if envs else
                                "UNSUPPORTED_BY_DESIGN" if not pixel else "GAP"),
            "backends": backends,
            "supported_devices": _devices(r),
            "fidelity": _fidelity(r),
            "gate_a": _gate_a(r, step8["gate_a"]) if pixel else
                      {"status": "UNSUPPORTED_BY_DESIGN", "raw": None, "per_device": {},
                       "failing_checks": [],
                       "note": "symbolic id: intentionally renderer-free, there is no frame to gate"},
            "cpu_tier": _tier(r, "cpu_tier"), "gpu_tier": _tier(r, "gpu_tier"),
            "variation": _variation(r),
            "swm_api_gate_f": {"status": "UNMEASURED",
                               "why": "Gate F is Workstream D's; no committed Step-8 Gate-F artifact "
                                      "exists at this HEAD"},
            "physics": {"status": "UNMEASURED",
                        "why": "no per-row physics verdict is carried in the Step-7 closure matrix; "
                               "check_step_matches_reference is judged on its own axis in "
                               "scratch/step4/certify.py and is not joined here"},
            "reproducibility": {"status": "PASS" if _gate_a(r, step8["gate_a"])["status"] == "PASS"
                                          else "UNMEASURED",
                                "why": "determinism, batch/batch-size/order/chunk invariance are "
                                       "mandatory Gate-A checks, so the Gate-A verdict carries them"},
            "semantic": {"status": "UNMEASURED",
                         "why": "Workstream H; no committed Step-8 semantic artifact at this HEAD"},
            "limitations": limitations(envs, r, step8),
            "frozen_corpus": {e: (step8["corpora"]["cells"][e]["array_sha256"][:16]
                                  if step8.get("corpora") and e in step8["corpora"]["cells"] else None)
                              for e in envs},
            "closed_in_step7": r.get("closed_in_step7"),
            "join_evidence": (r.get("join") or {}).get("evidence"),
        })

    return {"what_this_is": "the Step-8 support matrix for all 42 stable-worldmodel ids, generated "
                            "from committed artifacts by scratch/step8/report.py",
            "generated_at_head_sha": _sha(),
            "baseline_sha": "43ac95238f7472137619f3e69e7636e11dd088b1",
            "sources": {"coverage_matrix": str(COVERAGE_MATRIX.relative_to(ROOT)),
                        "coverage_matrix_integration_head": matrix.get("integration_head_verified"),
                        "census": sorted(str(p.relative_to(ROOT))
                                         for p in (ROOT / "scratch" / "census").glob("census_*.json")),
                        "classifier": "scratch/step3/certify.py:backend_class",
                        "step8_certification": sorted(str(p.relative_to(ROOT)) for p in S8.glob("*")
                                                      if p.is_file())},
            "status_vocabulary": list(STATUSES),
            "counts": {
                "rows": len(rows),
                "pixel_producing": sum(1 for r in rows if r["pixel_or_symbolic"] == "pixel"),
                "symbolic": sum(1 for r in rows if r["pixel_or_symbolic"] == "symbolic"),
                "render_covered": sum(1 for r in rows if r["render_coverage"] == "covered"),
                "gate_a": dict(Counter(r["gate_a"]["status"] for r in rows)),
                "cpu_tier_status": dict(Counter(r["cpu_tier"]["status"] for r in rows)),
                "gpu_tier_status": dict(Counter(r["gpu_tier"]["status"] for r in rows)),
                "variation_map": dict(Counter(r["variation"]["map_status"] for r in rows)),
                "backend_class": dict(Counter(r["backend_class"] for r in rows)),
            },
            "rows": rows}


def _cell(x) -> str:
    if isinstance(x, list):
        return ", ".join(f"`{i}`" for i in x) if x else "—"
    return f"`{x}`" if x not in (None, "", []) else "—"


def markdown(doc: dict) -> str:
    c = doc["counts"]
    L = ["# Step 8 — support matrix for all 42 `stable-worldmodel` ids", "",
         "!!! info \"Generated, not written\"", "",
         "    `python scratch/step8/report.py` regenerates this page and",
         "    `examples/results/step8/support_matrix.json` from committed artifacts. Every column is",
         "    read out of a file that is in the repository and cited below. Editing this page by hand",
         "    makes it wrong at the next regeneration, which is the point: a hand-maintained matrix",
         "    drifts from the evidence silently.", "",
         f"Baseline `{doc['baseline_sha']}` · generated at `{doc['generated_at_head_sha']}`", "",
         "## The five words", "",
         "Plan section 3 keeps these apart and this table never collapses them into a generic",
         "failure, because each carries a different obligation:", "",
         "| word | meaning | what it obliges |", "|---|---|---|",
         "| `PASS` | the claim holds and there is evidence | nothing |",
         "| `UNSUPPORTED_BY_DESIGN` | absent on purpose, and the env says so | nothing — it is closed |",
         "| `UNMEASURED` | nobody measured it | work, or an explicit decision not to |",
         "| `DOCUMENTED_LIMITATION` | known, measured, bounded | a record, not a campaign |",
         "| `UPSTREAM_FINDING` | the defect is SWM's or a dependency's | report upstream |", "",
         "`FAIL` is deliberately NOT one of the five: a real failure is a real failure, and this",
         "table reports it as such rather than dressing it as a limitation.", "",
         "The two tier columns use a sixth word, `MEASURED`, and only those columns do. A tier is a",
         "GRADE, not a gate: `CPU_REGRESSION` is a well-measured tier, and calling it `PASS` would",
         "read as \"fast enough\" while calling it `FAIL` would read as a defect. Neither is what a",
         "tier says. The tier string carries the grade; the word beside it says only whether a",
         "measurement exists at all.", "",
         "## Counts", "", "```text",
         f"rows                 {c['rows']}",
         f"pixel-producing      {c['pixel_producing']}",
         f"symbolic             {c['symbolic']}",
         f"render covered       {c['render_covered']}",
         f"gate A               {json.dumps(c['gate_a'], sort_keys=True)}",
         f"cpu tier status      {json.dumps(c['cpu_tier_status'], sort_keys=True)}",
         f"gpu tier status      {json.dumps(c['gpu_tier_status'], sort_keys=True)}",
         f"variation map        {json.dumps(c['variation_map'], sort_keys=True)}",
         f"backend class        {json.dumps(c['backend_class'], sort_keys=True)}",
         "```", "",
         "## The matrix", "",
         "| SWM id | cell(s) | class | kind | render | backend(s) | devices | fidelity tier | Gate A "
         "| reference/version | CPU tier | GPU tier | VariationMap | unsupported/dead leaves | "
         "Gate F | physics | reproducibility | semantic | limitations |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in doc["rows"]:
        dev = ", ".join(f"{d}:{v['status']}" for d, v in sorted(r["supported_devices"].items())) or "—"
        ga = r["gate_a"]["status"] + (f" ({', '.join(r['gate_a']['failing_checks'])})"
                                      if r["gate_a"]["failing_checks"] else "")
        ref = ", ".join(f"{k} {v}" for k, v in sorted((r["fidelity"]["reference_versions"] or {}).items())) or "—"
        lim = "; ".join(f"**{x['kind']}** {x['what']}" for x in r["limitations"] if x["kind"] != "note") or "—"
        L.append("| " + " | ".join([
            f"`{r['swm_id']}`", _cell(r["stable_envs_cells"]), r["backend_class"],
            r["pixel_or_symbolic"], r["render_coverage"], _cell(r["backends"]), dev,
            _cell(r["fidelity"]["tier"]), f"**{ga}**", ref,
            f"{r['cpu_tier']['tier']} ({r['cpu_tier']['status']})",
            f"{r['gpu_tier']['tier']} ({r['gpu_tier']['status']})",
            r["variation"]["map_status"], _cell(r["variation"]["unsupported_or_dead_leaves"]),
            r["swm_api_gate_f"]["status"], r["physics"]["status"],
            r["reproducibility"]["status"], r["semantic"]["status"], lim]) + " |")

    L += ["", "## What is UNMEASURED at this HEAD, and why", "",
          "These are absences of evidence, not failures, and each names the workstream that closes it:",
          "",
          "| column | why | closes with |", "|---|---|---|",
          "| Gate F / SWM API | no committed Step-8 Gate-F artifact exists yet | Workstream D |",
          "| physics | the Step-7 closure matrix carries no per-row physics verdict; "
          "`check_step_matches_reference` is judged on its own axis and is not joined here | "
          "Workstream E, on the final pass |",
          "| semantic | no committed Step-8 semantic artifact exists yet | Workstream H |",
          "| VariationMap (`missing` rows) | the map was never built for that row | Workstreams A/B/C |",
          "| CPU tiers marked `UNMEASURED` | the measurement was load-quarantined or never run | "
          "Workstream G |", "",
          "## Sources", "", "```text"]
    for k, v in sorted(doc["sources"].items()):
        L.append(f"{k}:")
        for x in (v if isinstance(v, list) else [v]):
            L.append(f"    {x}")
    L += ["```", ""]
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json-out", type=Path,
                    default=ROOT / "examples" / "results" / "step8" / "support_matrix.json")
    ap.add_argument("--md-out", type=Path,
                    default=ROOT / "docs" / "research" / "step8_support_matrix.md")
    a = ap.parse_args()
    doc = build()
    a.json_out.parent.mkdir(parents=True, exist_ok=True)
    a.json_out.write_text(json.dumps(doc, indent=1, sort_keys=True) + "\n")
    a.md_out.parent.mkdir(parents=True, exist_ok=True)
    a.md_out.write_text(markdown(doc))
    print(f"{a.json_out.relative_to(ROOT)}  {len(doc['rows'])} rows")
    print(f"{a.md_out.relative_to(ROOT)}")
    print(json.dumps(doc["counts"], indent=1, sort_keys=True))


if __name__ == "__main__":
    main()
