def _cell(x) -> str:
    if isinstance(x, list):
        return ", ".join(f"`{i}`" for i in x) if x else "—"
    return f"`{x}`" if x not in (None, "", []) else "—"


def markdown(doc: dict) -> str:
    c = doc["counts"]
    L = ["# Step 8 — support matrix for all 42 `stable-worldmodel` ids", "",
         "!!! info \"Generated, not written\"", "",
         "    `python scratch/step8/report.py` regenerates this page and",
         "    `examples/results/step8/support_matrix.json` from committed artifacts. Every column is",
         "    read out of a file that is in the repository and cited below. Editing this page by hand",
         "    makes it wrong at the next regeneration, which is the point: a hand-maintained matrix",
         "    drifts from the evidence silently.", "",
         f"Baseline `{doc['baseline_sha']}` · generated at `{doc['generated_at_head_sha']}`", "",
         "## The five words", "",
         "Plan section 3 keeps these apart and this table never collapses them into a generic",
         "failure, because each carries a different obligation:", "",
         "| word | meaning | what it obliges |", "|---|---|---|",
         "| `PASS` | the claim holds and there is evidence | nothing |",
         "| `UNSUPPORTED_BY_DESIGN` | absent on purpose, and the env says so | nothing — it is closed |",
         "| `UNMEASURED` | nobody measured it | work, or an explicit decision not to |",
         "| `DOCUMENTED_LIMITATION` | known, measured, bounded | a record, not a campaign |",
         "| `UPSTREAM_FINDING` | the defect is SWM's or a dependency's | report upstream |", "",
         "`FAIL` is deliberately NOT one of the five: a real failure is a real failure, and this",
         "table reports it as such rather than dressing it as a limitation.", "",
         "The two tier columns use a sixth word, `MEASURED`, and only those columns do. A tier is a",
         "GRADE, not a gate: `CPU_REGRESSION` is a well-measured tier, and calling it `PASS` would",
         "read as \"fast enough\" while calling it `FAIL` would read as a defect. Neither is what a",
         "tier says. The tier string carries the grade; the word beside it says only whether a",
         "measurement exists at all.", "",
         "## Counts", "", "```text",
         f"rows                 {c['rows']}",
         f"pixel-producing      {c['pixel_producing']}",
         f"symbolic             {c['symbolic']}",
         f"render covered       {c['render_covered']}",
         f"gate A               {json.dumps(c['gate_a'], sort_keys=True)}",
         f"cpu tier status      {json.dumps(c['cpu_tier_status'], sort_keys=True)}",
         f"gpu tier status      {json.dumps(c['gpu_tier_status'], sort_keys=True)}",
         f"variation map        {json.dumps(c['variation_map'], sort_keys=True)}",
         f"backend class        {json.dumps(c['backend_class'], sort_keys=True)}",
         "```", "",
         "## The matrix", "",
         "| SWM id | cell(s) | class | kind | render | backend(s) | devices | fidelity tier | Gate A "
         "| reference/version | CPU tier | GPU tier | VariationMap | unsupported/dead leaves | "
         "Gate F | physics | reproducibility | semantic | limitations |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in doc["rows"]:
        dev = ", ".join(f"{d}:{v['status']}" for d, v in sorted(r["supported_devices"].items())) or "—"
        ga = r["gate_a"]["status"] + (f" ({', '.join(r['gate_a']['failing_checks'])})"
                                      if r["gate_a"]["failing_checks"] else "")
        ref = ", ".join(f"{k} {v}" for k, v in sorted((r["fidelity"]["reference_versions"] or {}).items())) or "—"
        lim = "; ".join(f"**{x['kind']}** {x['what']}" for x in r["limitations"] if x["kind"] != "note") or "—"
        L.append("| " + " | ".join([
            f"`{r['swm_id']}`", _cell(r["stable_envs_cells"]), r["backend_class"],
            r["pixel_or_symbolic"], r["render_coverage"], _cell(r["backends"]), dev,
            _cell(r["fidelity"]["tier"]), f"**{ga}**", ref,
            f"{r['cpu_tier']['tier']} ({r['cpu_tier']['status']})",
            f"{r['gpu_tier']['tier']} ({r['gpu_tier']['status']})",
            r["variation"]["map_status"], _cell(r["variation"]["unsupported_or_dead_leaves"]),
            r["swm_api_gate_f"]["status"], r["physics"]["status"],
            r["reproducibility"]["status"], r["semantic"]["status"], lim]) + " |")

    L += ["", "## What is UNMEASURED at this HEAD, and why", "",
          "These are absences of evidence, not failures, and each names the workstream that closes it:",
          "",
          "| column | why | closes with |", "|---|---|---|",
          "| Gate F / SWM API | no committed Step-8 Gate-F artifact exists yet | Workstream D |",
          "| physics | the Step-7 closure matrix carries no per-row physics verdict; "
          "`check_step_matches_reference` is judged on its own axis and is not joined here | "
          "Workstream E, on the final pass |",
          "| semantic | no committed Step-8 semantic artifact exists yet | Workstream H |",
          "| VariationMap (`missing` rows) | the map was never built for that row | Workstreams A/B/C |",
          "| CPU tiers marked `UNMEASURED` | the measurement was load-quarantined or never run | "
          "Workstream G |", "",
          "## Sources", "", "```text"]
    for k, v in sorted(doc["sources"].items()):
        L.append(f"{k}:")
        for x in (v if isinstance(v, list) else [v]):
            L.append(f"    {x}")
    L += ["```", ""]
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json-out", type=Path,
                    default=ROOT / "examples" / "results" / "step8" / "support_matrix.json")
    ap.add_argument("--md-out", type=Path,
                    default=ROOT / "docs" / "research" / "step8_support_matrix.md")
    a = ap.parse_args()
    doc = build()
    a.json_out.parent.mkdir(parents=True, exist_ok=True)
    a.json_out.write_text(json.dumps(doc, indent=1, sort_keys=True) + "\n")
    a.md_out.parent.mkdir(parents=True, exist_ok=True)
    a.md_out.write_text(markdown(doc))
    print(f"{a.json_out.relative_to(ROOT)}  {len(doc['rows'])} rows")
    print(f"{a.md_out.relative_to(ROOT)}")
    print(json.dumps(doc["counts"], indent=1, sort_keys=True))


if __name__ == "__main__":
    main()
