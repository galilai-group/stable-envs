#!/usr/bin/env python
"""Generate leaf_classification.json and the per-id tables of the docs page FROM the module.

The classification lives in code (`compat/variation_maps/newcells.py`) and is tested there; this
script only renders it. Hand-maintaining the same table in prose is how a docs page and an artifact
come to disagree, which Step 8 explicitly reports as a defect rather than tolerating.

    python scratch/step8/variations-newcells/generate_report.py [--check]

``--check`` regenerates into memory and fails if the committed artifacts differ, so CI can tell that
someone edited the generated table by hand.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

from stable_envs.compat.variation_maps.newcells import (  # noqa: E402
    BUCKETS, CRAFTAX_NO_LEAVES, LEAF_CLASSIFICATION, NEWCELL_VARIATION_MAPS, PROBES,
    RECORDED_SWM_LEAVES,
)

OUT_JSON = ROOT / "examples/results/step8/variations-newcells/leaf_classification.json"
OUT_MD = ROOT / "examples/results/step8/variations-newcells/leaf_tables.md"
BASELINE_SHA = "43ac95238f7472137619f3e69e7636e11dd088b1"


def map_for(swm_id):
    return [m for m in NEWCELL_VARIATION_MAPS.values() if m.swm_id == swm_id][0]


def build():
    ids = sorted(RECORDED_SWM_LEAVES)
    per_id = {}
    totals = dict.fromkeys(BUCKETS, 0)
    for sid in ids:
        m = map_for(sid)
        cls = LEAF_CLASSIFICATION[sid]
        counts = dict.fromkeys(BUCKETS, 0)
        for rec in cls["leaves"].values():
            counts[rec["classification"]] += 1
            totals[rec["classification"]] += 1
        mapped = {t for t, _ in m.pairs().values()}
        per_id[sid] = {
            "our_envs": cls["our_envs"],
            "n_swm_leaves": len(RECORDED_SWM_LEAVES[sid]),
            "counts": counts,
            "complete": sorted(set(RECORDED_SWM_LEAVES[sid]) - mapped - set(m.swm_only)) == [],
            "config_note": cls.get("config_note"),
            "our_paths_mapped": {o: t for o, (t, _) in m.pairs().items()},
            "ours_only": dict(m.ours_only),
            "leaves": cls["leaves"],
        }
    doc = {
        "what_this_is": (
            "Step-8 Workstream C: every stable_worldmodel variation leaf offered by the Step-7 new "
            "cells and the OGB / Rocket / maze families, classified as mapped / unsupported / "
            "dead_upstream / not_applicable, with the measurement each verdict rests on."),
        "step": 8,
        "workstream": "variations-newcells",
        "baseline_sha": BASELINE_SHA,
        "generated_by": "scratch/step8/variations-newcells/generate_report.py",
        "source_of_truth": "stable_envs/compat/variation_maps/newcells.py",
        "buckets": list(BUCKETS),
        "probes": PROBES,
        "totals": {**totals, "n_ids": len(ids),
                   "n_leaves": sum(len(RECORDED_SWM_LEAVES[s]) for s in ids)},
        "ids": per_id,
        "zero_leaf_ids": CRAFTAX_NO_LEAVES,
    }
    return doc


def render_md(doc):
    L = ["# Step-8 Workstream C - per-id leaf tables", "",
         f"Generated by `{doc['generated_by']}` from `{doc['source_of_truth']}`.",
         f"Baseline `{doc['baseline_sha']}`.", "",
         "| bucket | count |", "|---|---|"]
    for b in doc["buckets"]:
        L.append(f"| `{b}` | {doc['totals'][b]} |")
    L += [f"| **total leaves** | **{doc['totals']['n_leaves']}** across {doc['totals']['n_ids']} ids |", ""]
    for sid, rec in doc["ids"].items():
        L += [f"## `{sid}`", "",
              f"stable-envs: {', '.join('`%s`' % e for e in rec['our_envs'])} - "
              f"{rec['n_swm_leaves']} swm leaves, "
              + ", ".join(f"{v} {k}" for k, v in rec["counts"].items() if v), ""]
        if rec["config_note"]:
            L += [f"> {rec['config_note']}", ""]
        L += ["| swm leaf | verdict | our path | evidence |", "|---|---|---|---|"]
        ours_by_theirs = {t: o for o, t in rec["our_paths_mapped"].items()}
        for leaf, r in sorted(rec["leaves"].items()):
            ev = r.get("evidence", "").split(" -- ")[-1] if r.get("evidence") else "-"
            L.append(f"| `{leaf}` | `{r['classification']}` | "
                     f"{'`%s`' % ours_by_theirs[leaf] if leaf in ours_by_theirs else '-'} | {ev} |")
        if rec["ours_only"]:
            L += ["", "Leaves we offer that swm does not:", ""]
            for k, v in sorted(rec["ours_only"].items()):
                L.append(f"- `{k}` - {v}")
        L.append("")
    L += ["## Ids offering zero leaves", "",
          "| swm id | stable-envs | leaves | verdict | evidence |", "|---|---|---|---|---|"]
    for sid, r in sorted(doc["zero_leaf_ids"].items()):
        L.append(f"| `{sid}` | {', '.join('`%s`' % e for e in r['our_envs'])} | "
                 f"{r['n_swm_leaves']} | `{r['classification']}` | {r['evidence']} |")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed artifacts differ from a fresh render")
    a = ap.parse_args()
    doc = build()
    js = json.dumps(doc, indent=1, sort_keys=True) + "\n"
    md = render_md(doc)
    if a.check:
        bad = [p for p, want in ((OUT_JSON, js), (OUT_MD, md))
               if not p.exists() or p.read_text() != want]
        if bad:
            raise SystemExit(f"stale generated artifacts: {[str(p) for p in bad]}; re-run this script")
        print("generated artifacts are up to date")
        return
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(js)
    OUT_MD.write_text(md)
    print(f"wrote {OUT_JSON.relative_to(ROOT)} and {OUT_MD.relative_to(ROOT)}")
    print("totals:", {k: doc["totals"][k] for k in doc["buckets"]})


if __name__ == "__main__":
    main()
