"""Emit the ``aacircle`` fringe stencils as literals, fitted jointly over colours AND backgrounds.

The weight SDL_gfx writes is a property of the ellipse walk, not of the colour, so a stencil that
depends on the colour would mean the fit is under-determined rather than that the renderer is. It is:
``alpha = (255*w) >> 8`` collides for ``w in {0, 1}``, and for some (colour, background) pairs several
weights round to the same byte, so fitting one colour at a time can pick a different representative
each time. Fitting every colour and background at once removes the ambiguity, and any radius that
still has no consistent answer is reported rather than papered over.

Fitting this way also keeps ``render/gfxdraw.py`` pure torch: the table goes in as a literal, so there
is no pygame import at render time and nothing to bake at construction.
"""
from __future__ import annotations

import os
import sys

os.environ.setdefault("SDL_VIDEODRIVER", "dummy")

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ref_gfx as G

COLOURS = [(0, 0, 0), (204, 77, 77), (129, 132, 203), (204, 204, 0), (128, 128, 128),
           (0, 204, 204), (255, 255, 255)]
BGS = [(255, 255, 255), (0, 0, 0), (100, 160, 200), (204, 77, 77), (17, 240, 90), (128, 128, 128)]
RADII = range(1, 17)
WS = list(range(257))                      # 256 == SOLID (pixelColor, not pixelColorWeight)


def observe(r):
    """(colour, bg) -> rendered surface, plus the fringe positions, for one radius."""
    import pygame
    from pygame import gfxdraw
    pygame.init()
    S = 4 * r + 9
    c = S // 2
    obs = {}
    for col in COLOURS:
        for bg in BGS:
            s = pygame.Surface((S, S))
            s.fill(bg)
            gfxdraw.aacircle(s, c, c, r, col)
            obs[(col, bg)] = np.transpose(np.array(pygame.surfarray.pixels3d(s)),
                                          (1, 0, 2)).astype(np.int64)
    fill = G.filled_circle_mask(c, c, r, S, S)
    touched = np.zeros((S, S), bool)
    for (col, bg), a in obs.items():
        touched |= (a != np.asarray(bg)).any(-1)
    ys, xs = np.where(touched & ~fill)
    return obs, list(zip(ys.tolist(), xs.tolist())), c


def main():
    tables = {}
    unresolved = []
    for r in RADII:
        obs, pts, c = observe(r)
        single = {(col, bg): np.stack([G.gfx_blend(np.asarray(col, np.int64),
                                                   np.asarray(bg, np.int64), w) for w in WS])
                  for col in COLOURS for bg in BGS}
        pair = {k: np.stack([np.stack([G.gfx_blend(np.asarray(k[0], np.int64), single[k][w1], w2)
                                       for w2 in WS]) for w1 in WS])
                for k in single}
        rows = []
        for (y, x) in pts:
            got = {k: obs[k][y, x] for k in single}
            ok = np.ones(len(WS), bool)
            for k in single:
                ok &= (single[k] == got[k]).all(-1)
            hit = np.where(ok)[0]
            if hit.size:
                rows.append((y - c, x - c, int(hit[0]), 0))
                continue
            ok2 = np.ones((len(WS), len(WS)), bool)
            for k in single:
                ok2 &= (pair[k] == got[k][None, None, :]).all(-1)
            h2 = np.argwhere(ok2)
            if not len(h2):
                unresolved.append((r, y - c, x - c))
                continue
            rows.append((y - c, x - c, int(h2[0][0]), 0))
            rows.append((y - c, x - c, int(h2[0][1]), 1))
        tables[r] = sorted(rows)
        print(f"  r={r:2d}: {len(pts)} fringe px -> {len(rows)} writes", file=sys.stderr)
    if unresolved:
        print(f"  UNRESOLVED (need >2 writes): {unresolved}", file=sys.stderr)

    print("#: ``gfxdraw.aacircle``'s fringe: radius -> ((dy, dx, weight, pass), ...).")
    print("#: ``weight`` 256 means ``pixelColor`` (solid); anything else goes through")
    print("#: ``pixelColorWeight`` at alpha ``(255*w) >> 8``. ``pass`` is 1 for the second of the two")
    print("#: writes ``aaellipseColor`` makes to a few pixels, which must land in order.")
    print("#: Generated by scratch/classic_control/gen_stencils.py, fitted jointly over 7 colours x 6")
    print("#: backgrounds, so the weights are the walk's own and carry no colour assumption.")
    print("AACIRCLE_FRINGE: dict[int, tuple[tuple[int, int, int, int], ...]] = {")
    for r in RADII:
        rows = ", ".join(f"({a}, {b}, {w}, {p})" for (a, b, w, p) in tables[r])
        print(f"    {r}: ({rows}),")
    print("}")


if __name__ == "__main__":
    main()
