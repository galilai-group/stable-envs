"""Assemble the Step 6 progress page from artifacts. In progress, and it says so.

Same discipline as Step 4 and Step 5: every number is read from `examples/results/step6/`, nothing
is hand-maintained, and the page states what has NOT been done as plainly as what has. Step 6 is a
long engineering loop and a page that only reports the parts that are finished is a page that
misleads by omission.

    python scratch/step6/report.py --out docs/research/step6_optimization.md
"""
from __future__ import annotations

import argparse
import json
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

#: What Step 6 has NOT done yet, stated up front. Removed from this list only when true.
NOT_YET = (
    "No renderer code has been modified. Every number here is a profile-before.",
    "No Step 6 worktree exists yet; the parent SHA is recorded below and nothing branches from it.",
    "No optimisation has been proposed, implemented, reviewed or merged.",
    "The frozen Step 4 corpora have been read and never written.",
)


def sh(*a) -> str:
    try:
        return subprocess.run(a, capture_output=True, text=True, timeout=30).stdout.strip()
    except Exception:
        return "unknown"


def esc(x) -> str:
    return str(x).replace("|", "\\|")


def tbl(rows, head) -> list[str]:
    if not rows:
        return ["_none yet._", ""]
    w = [max(len(esc(h)), *(len(esc(r[i])) for r in rows)) for i, h in enumerate(head)]
    out = ["| " + " | ".join(esc(h).ljust(w[i]) for i, h in enumerate(head)) + " |",
           "|" + "|".join("-" * (x + 2) for x in w) + "|"]
    for r in rows:
        out.append("| " + " | ".join(esc(v).ljust(w[i]) for i, v in enumerate(r)) + " |")
    return out + [""]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", type=Path, default=ROOT / "examples" / "results" / "step6")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "research" / "step6_optimization.md")
    args = ap.parse_args()

    plan = json.loads((args.results / "plan.json").read_text())["ranked"] \
        if (args.results / "plan.json").is_file() else []
    profiles = [json.loads(p.read_text())
                for p in sorted(args.results.glob("*/profile_before*/*.json"))]
    texture = [json.loads(p.read_text()) for p in sorted(args.results.glob("texture/*.json"))]

    L: list[str] = []
    A = L.append
    A("# Step 6 — optimising and repairing the existing renderer paths")
    A("")
    A("**Status: in progress.** Generated by `scratch/step6/report.py` from")
    A("`examples/results/step6/`; every number is computed from an artifact there.")
    A("")
    for n in NOT_YET:
        A(f"- {n}")
    A("")
    A(f"Baseline parent for every workstream: `{sh('git', '-C', str(ROOT), 'rev-parse', 'HEAD')[:12]}` "
      f"on `{sh('git', '-C', str(ROOT), 'branch', '--show-current')}`.")
    A("")

    # ------------------------------------------------------------------ ranking
    A("## Where the work is, measured")
    A("")
    A("Step 3 measured environment ROWS, Step 4 froze render-distinct CONFIGURATIONS, and Step 6")
    A("optimises shared PATHS. Those are three different units, so the ranking below joins them:")
    A("how many rows a path has below tier, how far the worst is from the frozen bar, and how many")
    A("frozen configurations a change there obliges us to replay (section 14).")
    A("")
    A("`slow` is measured and below tier. `none` is **never benchmarked** — the rows carry empty")
    A("evidence because the path does not exist on that device, which is a different job from")
    A("making a slow path fast.")
    A("")
    rows = []
    for o in plan:
        rows.append([o["workstream"] or "(unclaimed)", o["device"], o["backend_class"],
                     o["rows_at_tier"], o["rows_below"], o["rows_unmeasured"],
                     f"{o['worst_ratio']:.3f}" if o["worst_ratio"] is not None else "-",
                     f"{o['shortfall_x']:.0f}x" if o["shortfall_x"] else "-",
                     o["step4_replay_n"],
                     ", ".join(f"{k} x{v}" for k, v in sorted(
                         o["blocking_qualifiers"].items(), key=lambda kv: -kv[1])[:2]) or "-"])
    L.extend(tbl(rows, ["workstream", "dev", "class", "at tier", "slow", "never run",
                        "worst R", "gap", "replay", "blocking"]))
    A("Four things there disagree with the brief's ordering, and all four are measurements:")
    A("")
    A("- **`raycast3d` CPU is the smallest gap**, not a headline — 2x, with two rows already at")
    A("  tier — but it carries the largest replay obligation of any 2-D-scale workstream.")
    A("- **Fetch GPU's ratio already passes.** R = 5.34 against a class-S bar of 4; every slow row")
    A("  is blocked by `BATCH_SCALES_FAIL` alone. Optimising throughput would move a passing number.")
    A("- **`raster2d` CPU is the worst gap in the project** at 61x, ahead of `gfxdraw` CPU at 41x.")
    A("- **`cpu-3d` is mostly rows that were never benchmarked** — an architecture problem wearing")
    A("  an optimisation label.")
    A("")

    # ------------------------------------------------------------------ profiles
    A("## Profile-before")
    A("")
    A("The real public path (`env.render(states)`), CUDA-event timed with explicit synchronisation")
    A("on GPU, `perf_counter` on CPU, at the frozen mandatory batch sizes. `set_state` is timed")
    A("apart from `render`: per-env state unpacking in Python is a structural bottleneck in its own")
    A("right and folding it into render time is how it stays hidden. States come from the **frozen")
    A("Step 4 corpora**, read-only, so the profile describes the scenes Step 4 certified.")
    A("")
    A("Grouped by host, because a before/after across two machines is not a before/after.")
    A("")
    by_host: dict[str, list] = defaultdict(list)
    for d in profiles:
        by_host[d["host"].split(".")[0]].append(d)
    for host in sorted(by_host):
        ds = sorted(by_host[host], key=lambda d: (d.get("workstream") or "", d["env"]))
        gpu = ds[0].get("gpu")
        A(f"### `{host}` — {gpu or ds[0].get('cpu')}, {ds[0]['device']}, "
          f"{ds[0]['threads']} torch thread(s)")
        A("")
        cols = ["1", "16", "64", "256", "1024", "4096"]
        rows = []
        for d in ds:
            b = d["batches"]
            fps = [f"{b[c]['fps']:,.0f}" if c in b else "-" for c in cols]
            have = [b[c]["fps"] for c in cols if c in b]
            scale = f"{have[-1] / have[0]:.1f}x" if len(have) > 1 and have[0] else "-"
            ops = max(v["trace"]["op_count"] for v in b.values())
            rows.append([d["env"], (d.get("workstream") or "").replace("step6/", ""),
                         f"{d['size']}px", *fps, scale, f"{ops:,}"])
        L.extend(tbl(rows, ["env", "workstream", "frame", *[f"B={c}" for c in cols],
                            "scale", "ops/render"]))
    A("`scale` is the largest batch measured over B=1 — for GPU rows the frozen `BATCH_SCALES` bar")
    A("is 20x at B=4096, and it applies only where the full sweep completed.")
    A("")

    # ------------------------------------------------------------------ texture
    if len(texture) > 1:
        A("## An upstream cause, isolated")
        A("")
        A("Found while explaining a Step 5 result, and it reaches into Step 6's correctness work.")
        A("`suite.load('reacher','hard')` renders dm_control's checkerboard floor under one MuJoCo")
        A("and not the other, from a byte-identical texture declaration:")
        A("")
        rows = [[t["mujoco"], f"{t['quadrant_spread']:.2f}", t["distinct_colours"],
                 f"{t['declaration']['tex_width']}x{t['declaration']['tex_height']}",
                 str(t["declaration"]["mat_texrepeat"]), t["declaration"]["mat_texuniform"]]
                for t in sorted(texture, key=lambda t: t["mujoco"])]
        L.extend(tbl(rows, ["mujoco", "quadrant contrast", "distinct colours", "texture",
                            "texrepeat", "texuniform"]))
        A("Quadrant contrast is the light-vs-dark split of the floor: present at 40.68, gone at")
        A("7.49. Nothing in dm_control, `stable_worldmodel` or stable-envs differs between the two")
        A("runs. **This is upstream of the whole project.**")
        A("")
        A("Why it matters here: Step 4 recorded that `DMCCheetahRun`, `DMCHopperHop` and")
        A("`DMCWalkerWalk` **declared** their visual-fidelity contracts under mujoco 3.11 and were")
        A("**measured** under 3.12, with the residual concentrated in the skybox — which is also a")
        A("texture. One upstream change may therefore account for three of the five frozen Step 4")
        A("failures. That is a hypothesis with a test queued (replay the frozen corpora under 3.11),")
        A("not a result.")
        A("")

    # ------------------------------------------------------------------ findings
    fnd = args.results / "findings.md"
    if fnd.is_file():
        A("## Findings so far")
        A("")
        A(f"Recorded in [`{fnd.relative_to(ROOT)}`]({fnd.relative_to(ROOT.parent / ROOT.name)}), "
          f"before any edit. Summarised:")
        A("")
        for line in fnd.read_text().splitlines():
            if line.startswith("## "):
                A(f"- **{line[3:].strip()}**")
        A("")

    A("## What happens next")
    A("")
    A("1. Read the queued 3.11 replay: does the upstream texture change explain Cheetah, Hopper")
    A("   and Walker?")
    A("2. Profile-before for the two Scene2D envs, which cannot run on a Triton host until the")
    A("   dispatch defect is fixed — so their profile follows their fix rather than preceding it.")
    A("3. One worktree per measured bottleneck off the baseline SHA, in the ranked order above.")
    A("4. Per workstream: profile note, smallest structural patch, targeted tests, frozen Step 4")
    A("   replay across **all** affected configurations, performance sweep, record.")
    A("")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(L) + "\n")
    print(f"wrote {args.out} ({len(L)} lines) from {len(profiles)} profiles, {len(plan)} workstreams")


if __name__ == "__main__":
    main()
